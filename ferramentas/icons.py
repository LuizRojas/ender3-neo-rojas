def parse(art):
    rows = [r for r in art.strip("\n").split("\n")]
    assert len(rows) == 16, len(rows)
    for r in rows: assert len(r) == 16, r
    return rows

def to_bytes(rows):
    out = []
    for r in rows:
        v = int(r.replace("#", "1").replace(".", "0"), 2)
        out += [v >> 8, v & 0xFF]
    return out

def header():
    lines = ["// Gerado por tools/icons.py - icones 16x16 do menu em grade", "#pragma once", ""]
    for name, art in ICONS.items():
        b = to_bytes(parse(art))
        hexs = ", ".join("0x%02X" % x for x in b)
        lines.append("const unsigned char grid_icon_%s[] PROGMEM = { %s };" % (name, hexs))
    return "\n".join(lines) + "\n"

if __name__ == "__main__":
    open(sys.argv[1], "w").write(header())
